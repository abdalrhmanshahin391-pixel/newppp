export function strokesFor(char: string): string[] | null {
  if (char === " ") return [];
  const [base, ...marks] = Array.from(char.normalize("NFD"));
  const glyph = alphabet[base];
  if (!glyph) return null;
  const accents: Record<string, string> = {
    "\u0308": "M2 0 l0.2 -0.3 M7 0 l0.2 -0.3",
    "\u0301": "M3 1 L7 -2",
    "\u0300": "M7 1 L3 -2",
    "\u0302": "M2 1 L5 -2 L8 1",
    "\u0303": "M1 1 Q3 -2 5 0 T9 -1",
    "\u0327": "M5 15 q2 3 -2 3",
  };
  if (marks.some((mark) => !accents[mark])) return null;
  return [glyph, ...marks.map((mark) => accents[mark])].flatMap(
    (path) => path.match(/M[^M]+/g) ?? [],
  );
}
