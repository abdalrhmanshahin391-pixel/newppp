-- Durable, private history for Rita's free-conversation mode. Lessons remain
-- deliberately separate. One conversation can span several realtime sessions.

create table if not exists public.rita_free_conversations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null default 'New conversation'
    check (char_length(title) between 1 and 120),
  language_preference text not null default 'automatic',
  dialect_preference text not null default 'ar-JO',
  message_count integer not null default 0 check (message_count >= 0),
  last_message_at timestamptz,
  archived_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists rita_free_conversations_user_recent_idx
  on public.rita_free_conversations(user_id, coalesce(last_message_at, created_at) desc)
  where archived_at is null;

create table if not exists public.rita_free_conversation_messages (
  id bigint generated by default as identity primary key,
  client_message_id uuid not null unique,
  conversation_id uuid not null references public.rita_free_conversations(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  session_id uuid references public.rita_v3_sessions(id) on delete set null,
  role text not null check (role in ('user', 'assistant')),
  content text not null check (char_length(btrim(content)) between 1 and 12000),
  generated_content text check (generated_content is null or char_length(generated_content) <= 12000),
  spoken_content text check (spoken_content is null or char_length(spoken_content) <= 12000),
  source text not null default 'voice' check (source in ('voice', 'text', 'scripted')),
  delivery_status text not null default 'completed'
    check (delivery_status in ('completed', 'interrupted', 'incomplete')),
  created_at timestamptz not null default now()
);

create index if not exists rita_free_messages_conversation_order_idx
  on public.rita_free_conversation_messages(conversation_id, created_at, id);
create index if not exists rita_free_messages_session_idx
  on public.rita_free_conversation_messages(session_id)
  where session_id is not null;

alter table public.rita_v3_sessions
  add column if not exists conversation_id uuid
    references public.rita_free_conversations(id) on delete set null;

create index if not exists rita_v3_sessions_conversation_started_idx
  on public.rita_v3_sessions(conversation_id, started_at)
  where conversation_id is not null;

-- Preserve the existing signed-in-user runtime writes while preventing a
-- caller from linking their session to another learner's conversation.
drop policy if exists "users create own rita v3 sessions" on public.rita_v3_sessions;
create policy "users create own rita v3 sessions"
  on public.rita_v3_sessions
  for insert to authenticated
  with check (
    auth.uid() = user_id
    and (
      conversation_id is null
      or exists (
        select 1 from public.rita_free_conversations conversation
        where conversation.id = conversation_id
          and conversation.user_id = auth.uid()
      )
    )
  );

drop policy if exists "users update own rita v3 sessions" on public.rita_v3_sessions;
create policy "users update own rita v3 sessions"
  on public.rita_v3_sessions
  for update to authenticated
  using (auth.uid() = user_id)
  with check (
    auth.uid() = user_id
    and (
      conversation_id is null
      or exists (
        select 1 from public.rita_free_conversations conversation
        where conversation.id = conversation_id
          and conversation.user_id = auth.uid()
      )
    )
  );

