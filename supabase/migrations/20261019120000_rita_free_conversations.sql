-- Keep list metadata correct in the database, not in a fallible browser. The
-- first real learner message becomes the title; no AI call or extra latency.
create or replace function public.refresh_rita_free_conversation()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  target_conversation uuid;
  first_user_text text;
begin
  if tg_op = 'DELETE' then
    target_conversation := old.conversation_id;
  else
    target_conversation := new.conversation_id;
  end if;

  select left(regexp_replace(btrim(message.content), '\s+', ' ', 'g'), 72)
    into first_user_text
  from public.rita_free_conversation_messages message
  where message.conversation_id = target_conversation
    and message.role = 'user'
  order by message.created_at, message.id
  limit 1;

  update public.rita_free_conversations conversation
  set message_count = (
        select count(*)::integer
        from public.rita_free_conversation_messages message
        where message.conversation_id = target_conversation
      ),
      last_message_at = (
        select max(message.created_at)
        from public.rita_free_conversation_messages message
        where message.conversation_id = target_conversation
      ),
      title = case
        when conversation.title = 'New conversation' and first_user_text is not null
          then first_user_text
        else conversation.title
      end,
      updated_at = now()
  where conversation.id = target_conversation;

  if tg_op = 'DELETE' then
    return old;
  end if;
  return new;
end;
$$;

drop trigger if exists refresh_rita_free_conversation_after_message
  on public.rita_free_conversation_messages;
create trigger refresh_rita_free_conversation_after_message
after insert or update or delete on public.rita_free_conversation_messages
for each row execute function public.refresh_rita_free_conversation();

